/* Ines Morrow Photography — site scripts. Vanilla JavaScript, no dependencies.
   The LENS object above holds the galleries, packages and proofing set; edit it to change content
   that is rendered by script (gallery pages, the lightbox, the package calculator). */
(function () {
  'use strict';

  /* localStorage, or memory when it's blocked or a save fails (storage full). Memory is read first, so a change
     that couldn't be saved still shows for this page view. */
  var safeStorage = (function () {
    var local = null;
    try { local = window.localStorage; local.getItem('_'); } catch (e) { local = null; /* blocked */ }
    var memory = Object.create(null);
    return {
      getItem: function (key) {
        if (key in memory) return memory[key];
        try { return local ? local.getItem(key) : null; } catch (e) { return null; }
      },
      setItem: function (key, value) {
        if (local) {
          try { local.setItem(key, String(value)); delete memory[key]; return; } catch (e) { /* full */ }
        }
        memory[key] = String(value);
      },
      removeItem: function (key) {
        delete memory[key];
        if (local) { try { local.removeItem(key); } catch (e) { /* blocked */ } }
      }
    };
  })();

  var $ = function (sel, el) { return (el || document).querySelector(sel); };
  var $$ = function (sel, el) { return Array.prototype.slice.call((el || document).querySelectorAll(sel)); };
  var reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  var euro = function (n) { return '$' + Math.round(n).toLocaleString('en-US'); };
  var esc = function (s) {
    return String(s).replace(/[&<>"']/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]; });
  };

  /* ---------- Years ----------
     [data-year] shows this year (the footer copyright); [data-year-ahead="1"] shows next year (the "Now
     booking" lines and the availability note), so the demo never advertises a season that has passed.
     Replace the spans with plain text to show fixed years. */
  var thisYear = new Date().getFullYear();
  $$('[data-year]').forEach(function (el) { el.textContent = String(thisYear); });
  $$('[data-year-ahead]').forEach(function (el) {
    var n = parseInt(el.getAttribute('data-year-ahead'), 10);
    if (n >= 0 && n <= 9) el.textContent = String(thisYear + n);
  });

  /* ---------- Header ---------- */
  var header = $('[data-header]');
  function onScroll() { header.classList.toggle('is-scrolled', window.scrollY > 24); }
  window.addEventListener('scroll', onScroll, { passive: true });
  onScroll();

  /* ---------- Mobile menu ---------- */
  var menuBtn = $('[data-menu-button]');
  var menu = $('#mobile-menu');
  function setMenu(open) {
    menu.hidden = !open;
    menuBtn.setAttribute('aria-expanded', String(open));
    menuBtn.setAttribute('aria-label', open ? 'Close menu' : 'Open menu');
    header.classList.toggle('menu-open', open);
    document.body.classList.toggle('overflow-hidden', open);
    if (open) { var first = $('a', menu); if (first) first.focus(); }
  }
  if (menuBtn && menu) {
    menuBtn.addEventListener('click', function () { setMenu(menu.hidden); });
    document.addEventListener('keydown', function (e) {
      if (e.key === 'Escape' && !menu.hidden) { setMenu(false); menuBtn.focus(); }
    });
    window.matchMedia('(min-width: 1024px)').addEventListener('change', function (e) { if (e.matches) setMenu(false); });
  }

  /* ---------- Scroll reveal ----------
     Revealing an element also reveals everything before it, so jumping down the page
     (End key, anchors) never leaves hidden content behind. */
  var reveals = $$('.reveal');
  function revealUpTo(el) {
    var i = reveals.indexOf(el);
    for (var j = 0; j <= i; j++) reveals[j].classList.add('is-in');
  }
  var io = null;
  if (!reduceMotion && 'IntersectionObserver' in window) {
    io = new IntersectionObserver(function (entries) {
      entries.forEach(function (en) {
        if (en.isIntersecting) { revealUpTo(en.target); io.unobserve(en.target); }
      });
    }, { rootMargin: '0px 0px -6% 0px' });
    reveals.forEach(function (el) { io.observe(el); });
  } else {
    reveals.forEach(function (el) { el.classList.add('is-in'); });
  }
  // Elements added by script later (gallery pages) reveal straight away.
  function showNow(scope) { $$('.reveal', scope).forEach(function (el) { el.classList.add('is-in'); }); }

  /* ---------- Home hero slideshow ---------- */
  var hero = $('[data-hero]');
  if (hero) {
    var slides = $$('[data-slide]', hero);
    var dots = $$('[data-dot]', hero);
    var caption = $('[data-hero-caption]', hero);
    var toggle = $('[data-hero-toggle]', hero);
    var current = 0;
    var timer = null;
    var paused = reduceMotion;

    // The caption is only announced when the visitor changes the photo, never on autoplay.
    var show = function (n, announce) {
      current = (n + slides.length) % slides.length;
      slides.forEach(function (s, i) {
        var on = i === current;
        s.classList.toggle('is-active', on);
        if (on) s.removeAttribute('aria-hidden'); else s.setAttribute('aria-hidden', 'true');
        if (on) { var im = $('img', s); if (im) im.loading = 'eager'; }
      });
      dots.forEach(function (d, i) { d.setAttribute('aria-current', String(i === current)); });
      caption.setAttribute('aria-live', announce ? 'polite' : 'off');
      caption.textContent = slides[current].dataset.caption;
    };
    var play = function () {
      clearInterval(timer);
      if (!paused) timer = setInterval(function () { show(current + 1); }, 6500);
    };
    var setPaused = function (p) {
      paused = p;
      toggle.setAttribute('aria-label', p ? 'Play slideshow' : 'Pause slideshow');
      // SVG elements have no .hidden property, so toggle the attribute itself.
      $('[data-icon-pause]', toggle).toggleAttribute('hidden', p);
      $('[data-icon-play]', toggle).toggleAttribute('hidden', !p);
      play();
    };
    dots.forEach(function (d, i) { d.addEventListener('click', function () { show(i, true); play(); }); });
    toggle.addEventListener('click', function () { setPaused(!paused); });
    show(0);
    setPaused(paused);
  }

  /* ---------- Portfolio filter (shareable as portfolio.html#weddings) ---------- */
  var filterList = $('[data-filter-list]');
  if (filterList) {
    var buttons = $$('[data-filter]');
    var cards = $$('[data-category]', filterList);
    var countEl = $('[data-filter-count]');
    var emptyEl = $('[data-filter-empty]');
    var apply = function (key, updateHash) {
      if (!buttons.some(function (b) { return b.dataset.filter === key; })) key = 'all';
      var shown = 0;
      cards.forEach(function (c) {
        var on = key === 'all' || c.dataset.category === key;
        c.hidden = !on;
        if (on) { shown++; c.classList.add('is-in'); }
      });
      buttons.forEach(function (b) { b.setAttribute('aria-pressed', String(b.dataset.filter === key)); });
      countEl.textContent = shown + (shown === 1 ? ' gallery' : ' galleries');
      emptyEl.hidden = shown > 0;
      if (updateHash) history.replaceState(null, '', key === 'all' ? location.pathname + location.search : '#' + key);
    };
    buttons.forEach(function (b) { b.addEventListener('click', function () { apply(b.dataset.filter, true); }); });
    apply(location.hash.slice(1), false);
    window.addEventListener('hashchange', function () { apply(location.hash.slice(1), false); });
  }

  /* ---------- Gallery page: render the gallery from ?g=<slug> ---------- */
  var grid = $('[data-gallery]');
  var gallery = null;
  if (grid) {
    var slug = new URLSearchParams(location.search).get('g');
    var index = 0;
    LENS.galleries.forEach(function (g, i) { if (g.slug === slug) index = i; });
    gallery = LENS.galleries[index];
    if (gallery.slug !== grid.dataset.gallery) {
      $('[data-g-title]').textContent = gallery.title;
      $('[data-g-category]').textContent = gallery.category;
      $('[data-g-summary]').textContent = gallery.summary;
      $('[data-g-location]').textContent = gallery.location;
      $('[data-g-date]').textContent = gallery.date;
      $('[data-g-count]').textContent = gallery.photos.length;
      document.title = gallery.title + ' — Ines Morrow Photography';
      var desc = $('meta[name="description"]');
      if (desc) desc.setAttribute('content', gallery.summary);
      grid.dataset.gallery = gallery.slug;
      grid.innerHTML = gallery.photos.map(function (p, i) {
        return '<figure class="reveal is-in">' +
          '<button type="button" class="frame group block w-full cursor-zoom-in" data-lightbox-open="' + i + '" aria-label="Open photo ' + (i + 1) + ' of ' + gallery.photos.length + ': ' + esc(p.caption) + '">' +
          '<img src="assets/img/photos/' + p.id + '.svg" alt="' + esc(p.alt) + '" width="' + p.w + '" height="' + p.h + '" loading="lazy" decoding="async"></button>' +
          '<figcaption class="mt-2 text-sm text-muted">' + esc(p.caption) + '</figcaption></figure>';
      }).join('');
      showNow(grid);
    }
    var prev = LENS.galleries[(index - 1 + LENS.galleries.length) % LENS.galleries.length];
    var next = LENS.galleries[(index + 1) % LENS.galleries.length];
    $('[data-g-prev]').href = 'gallery.html?g=' + prev.slug;
    $('[data-g-prev-title]').textContent = prev.title;
    $('[data-g-next]').href = 'gallery.html?g=' + next.slug;
    $('[data-g-next-title]').textContent = next.title;
  }

  /* ---------- Lightbox (native <dialog>: focus is trapped and Esc closes it) ---------- */
  var lb = $('[data-lightbox]');
  if (lb && gallery) {
    var lbImg = $('[data-lb-img]', lb);
    var lbCaption = $('[data-lb-caption]', lb);
    var lbCounter = $('[data-lb-counter]', lb);
    var at = 0;
    var opener = null;
    var render = function () {
      var p = gallery.photos[at];
      lbImg.src = 'assets/img/photos/' + p.id + '.svg';
      lbImg.alt = p.alt;
      lbImg.width = p.w;
      lbImg.height = p.h;
      lbCaption.textContent = p.caption;
      lbCounter.textContent = (at + 1) + ' / ' + gallery.photos.length;
      // Warm the cache for the next photo.
      var n = gallery.photos[(at + 1) % gallery.photos.length];
      new Image().src = 'assets/img/photos/' + n.id + '.svg';
    };
    var go = function (d) { at = (at + d + gallery.photos.length) % gallery.photos.length; render(); };
    grid.addEventListener('click', function (e) {
      var b = e.target.closest('[data-lightbox-open]');
      if (!b) return;
      opener = b;
      at = Number(b.dataset.lightboxOpen) || 0;
      render();
      lb.showModal();
      $('[data-lb-close]', lb).focus();
    });
    $('[data-lb-prev]', lb).addEventListener('click', function () { go(-1); });
    $('[data-lb-next]', lb).addEventListener('click', function () { go(1); });
    $('[data-lb-close]', lb).addEventListener('click', function () { lb.close(); });
    lb.addEventListener('keydown', function (e) {
      if (e.key === 'ArrowLeft') { e.preventDefault(); go(-1); }
      if (e.key === 'ArrowRight') { e.preventDefault(); go(1); }
    });
    lb.addEventListener('close', function () { if (opener) opener.focus(); });
    // Clicking the dark area around the photo closes the viewer.
    $('[data-lb-stage]', lb).addEventListener('click', function (e) { if (e.target === e.currentTarget) lb.close(); });
    // Swipe left/right on touch screens.
    var startX = null;
    lb.addEventListener('pointerdown', function (e) { startX = e.clientX; });
    lb.addEventListener('pointerup', function (e) {
      if (startX === null) return;
      var dx = e.clientX - startX;
      startX = null;
      if (Math.abs(dx) > 50 && e.pointerType !== 'mouse') go(dx < 0 ? 1 : -1);
    });
  }

  /* ---------- Package calculator ---------- */
  var calc = $('[data-calculator]');
  if (calc) {
    var extra = 0;
    var MAX_EXTRA = 6;
    var addons = $$('input[name="addon"]', calc);
    var notes = {};
    addons.forEach(function (a) { notes[a.value] = $('[data-addon-note="' + a.value + '"]', calc).textContent; });
    var update = function () {
      var picked = $('input[name="package"]:checked', calc);
      var id = picked ? picked.value : 'signature';
      var pkg = LENS.packages[id];
      var included = LENS.included[id] || [];
      addons.forEach(function (a) {
        var inc = included.indexOf(a.value) !== -1;
        if (inc) a.checked = true;
        // Uncheck add-ons that were only checked because the previous package included them.
        else if (a.dataset.auto === 'true') a.checked = false;
        a.dataset.auto = String(inc);
        a.disabled = inc;
        $('[data-addon-note="' + a.value + '"]', calc).textContent = inc ? 'Included in ' + pkg.name : notes[a.value];
      });
      var chosen = addons.filter(function (a) { return a.checked && !a.disabled; });
      var total = pkg.price + extra * LENS.extraHour + chosen.reduce(function (sum, a) { return sum + Number(a.dataset.price); }, 0);
      $('[data-calc-summary]', calc).textContent = pkg.name + ' · ' + (pkg.hours + extra) + ' hours';
      $('[data-hours-value]', calc).textContent = String(extra);
      $('[data-calc-total]', calc).textContent = euro(total);
      $('[data-calc-deposit]', calc).textContent = euro(total * LENS.deposit);
      $('[data-hours-step="-1"]', calc).disabled = extra === 0;
      $('[data-hours-step="1"]', calc).disabled = extra === MAX_EXTRA;
      var q = 'package=' + id + (extra ? '&hours=' + extra : '') + (chosen.length ? '&addons=' + chosen.map(function (a) { return a.value; }).join(',') : '');
      $('[data-calc-enquire]', calc).href = 'contact.html?' + q;
    };
    calc.addEventListener('change', update);
    $$('[data-hours-step]', calc).forEach(function (b) {
      b.addEventListener('click', function () {
        extra = Math.max(0, Math.min(MAX_EXTRA, extra + Number(b.dataset.hoursStep)));
        update();
      });
    });
    calc.addEventListener('submit', function (e) { e.preventDefault(); });
    update();
  }

  // A short reference for confirmations, like IM-7K2Q (no 0/O or 1/I to misread).
  function makeRef(prefix) {
    var chars = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789', out = '';
    for (var i = 0; i < 4; i++) out += chars.charAt(Math.floor(Math.random() * chars.length));
    return prefix + '-' + out;
  }

  /* ---------- Client proofing ----------
     Selections are kept in localStorage. Stored data is validated on every read
     (unknown ids, duplicates and over-limit lists are dropped) and healed in place. */
  var proofGrid = $('[data-proof-grid]');
  if (proofGrid) {
    var KEY = 'lens-proofing-v1';
    var LIMIT = LENS.proofLimit;
    var ids = LENS.proofIds;
    var load = function () {
      var raw = null;
      try { raw = JSON.parse(safeStorage.getItem(KEY)); } catch (e) { raw = null; }
      var list = Array.isArray(raw) ? raw : [];
      var clean = [];
      list.forEach(function (x) { if (typeof x === 'string' && ids.indexOf(x) !== -1 && clean.indexOf(x) === -1 && clean.length < LIMIT) clean.push(x); });
      if (JSON.stringify(clean) !== JSON.stringify(raw)) save(clean);
      return clean;
    };
    var save = function (list) {
      try { safeStorage.setItem(KEY, JSON.stringify(list)); } catch (e) { /* storage full or blocked: keep working in memory */ }
      hideDone();
    };
    // A sent selection is out of date as soon as it changes, so hide the confirmation.
    var hideDone = function () { var d = $('[data-proof-done]'); if (d) d.hidden = true; };
    var selected = load();
    var view = 'all';
    var cardsP = $$('[data-proof]', proofGrid);
    var msg = $('[data-proof-message]');
    var say = function (text) { msg.textContent = text; msg.classList.toggle('hidden', !text); };

    var renderProof = function () {
      cardsP.forEach(function (card, n) {
        var on = selected.indexOf(card.dataset.proof) !== -1;
        var btn = $('[data-proof-toggle]', card);
        card.dataset.selected = String(on);
        btn.setAttribute('aria-pressed', String(on));
        btn.setAttribute('aria-label', (on ? 'Remove photo ' : 'Select photo ') + (n + 1) + (on ? ' from selection' : ''));
        $('[data-proof-state]', card).textContent = on ? 'Selected' : '';
        card.hidden = view === 'selected' && !on;
        card.classList.add('is-in');
      });
      $('[data-proof-count]').textContent = String(selected.length);
      $('[data-proof-bar]').style.width = (selected.length / LIMIT * 100) + '%';
      $('[data-proof-hint]').textContent = selected.length >= LIMIT ? '· album full' : '· ' + (LIMIT - selected.length) + ' left';
      $('[data-proof-empty]').hidden = !(view === 'selected' && selected.length === 0);
      $$('[data-proof-view]').forEach(function (b) { b.setAttribute('aria-pressed', String(b.dataset.proofView === view)); });
    };
    proofGrid.addEventListener('click', function (e) {
      var btn = e.target.closest('[data-proof-toggle]');
      if (!btn) return;
      var id = btn.closest('[data-proof]').dataset.proof;
      var i = selected.indexOf(id);
      if (i !== -1) { selected.splice(i, 1); say(''); }
      else if (selected.length >= LIMIT) { say('Your album holds ' + LIMIT + ' photographs. Remove one to choose another.'); return; }
      else { selected.push(id); say(''); }
      save(selected);
      renderProof();
    });
    $$('[data-proof-view]').forEach(function (b) { b.addEventListener('click', function () { view = b.dataset.proofView; renderProof(); }); });
    $('[data-proof-clear]').addEventListener('click', function () { selected = []; save(selected); say('Selection cleared.'); renderProof(); });
    $('[data-proof-submit]').addEventListener('click', function () {
      if (!selected.length) { say('Choose at least one photograph before sending your selection.'); return; }
      say('');
      var done = $('[data-proof-done]');
      $('[data-proof-done-text]').textContent = selected.length + ' of ' + LIMIT + ' photographs chosen for the album.';
      $('[data-proof-ref]').textContent = makeRef('IM');
      done.hidden = false;
      done.focus();
    });
    // Keep tabs in sync when the selection changes in another window.
    window.addEventListener('storage', function (e) { if (e.key === KEY) { selected = load(); hideDone(); renderProof(); } });
    renderProof();
  }

  /* ---------- Inquiry form ---------- */
  var form = $('[data-enquiry]');
  if (form) {
    var params = new URLSearchParams(location.search);
    var pkgSel = $('#c-package', form);
    var wanted = params.get('package');
    // Only real package ids (not inherited object keys such as "constructor") preselect the form.
    if (wanted && Object.prototype.hasOwnProperty.call(LENS.packages, wanted)) {
      pkgSel.value = wanted;
      $('#c-type', form).value = LENS.packages[wanted].kind === 'Portrait' ? 'portrait' : 'wedding';
    }
    var today = new Date();
    var iso = new Date(today.getTime() - today.getTimezoneOffset() * 60000).toISOString().slice(0, 10);
    $('#c-date', form).min = iso;

    var check = function (field) {
      var v = field.value.trim();
      var m = '';
      var type = $('#c-type', form).value;
      if (field.required && !v) m = field.tagName === 'SELECT' ? 'Please choose an option.' : 'Please fill this in.';
      else if (field.type === 'email' && v && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(v)) m = 'Please enter a valid email address.';
      else if (field.name === 'message' && v.length < 20) m = 'A sentence or two helps me reply properly (20 characters or more).';
      else if (field.name === 'date') {
        if (!v && (type === 'wedding' || type === 'elopement')) m = 'Please add your date, even if it\'s approximate.';
        else if (v && v < iso) m = 'Please choose a date in the future.';
      }
      var errId = field.id + '-error';
      var err = document.getElementById(errId);
      var hint = field.id === 'c-date' ? ' c-date-hint' : '';
      if (m) {
        if (!err) { err = document.createElement('p'); err.className = 'error'; err.id = errId; field.parentNode.appendChild(err); }
        err.textContent = m;
        field.setAttribute('aria-invalid', 'true');
        field.setAttribute('aria-describedby', (errId + hint).trim());
      } else {
        if (err) err.remove();
        field.removeAttribute('aria-invalid');
        if (hint) field.setAttribute('aria-describedby', 'c-date-hint'); else field.removeAttribute('aria-describedby');
      }
      return !m;
    };
    var fields = $$('input, select, textarea', form);
    fields.forEach(function (f) {
      f.addEventListener('blur', function () { if (f.value || f.getAttribute('aria-invalid')) check(f); });
      f.addEventListener('input', function () { if (f.getAttribute('aria-invalid')) check(f); });
    });
    $('#c-type', form).addEventListener('change', function () { var d = $('#c-date', form); if (d.getAttribute('aria-invalid')) check(d); });
    form.addEventListener('submit', function (e) {
      e.preventDefault();
      var ok = fields.map(check).every(Boolean);
      if (!ok) { $('[aria-invalid="true"]', form).focus(); return; }
      // To receive inquiries, send the data to your form service here, e.g.
      // fetch('https://formspree.io/f/your-id', { method: 'POST', body: new FormData(form), headers: { Accept: 'application/json' } })
      var success = $('[data-success]', form);
      $('[data-ref]', success).textContent = makeRef('IM');
      success.classList.remove('hidden');
      success.focus();
    });
    $('[data-reset]', form).addEventListener('click', function () {
      form.reset();
      $('[data-success]', form).classList.add('hidden');
      $('#c-name', form).focus();
    });
  }
})();

/* ---------- Back to top ----------
   A button that fades in after you scroll about one screen down. It returns to
   the top (instantly if the visitor prefers reduced motion) and moves keyboard
   focus to the main content. It lifts itself above toasts so they never overlap.
   Mark your own UI with data-back-to-top-avoid (lift above it) or data-back-to-top-hide
   (hide while covering it). To remove the button: delete this block and the .back-to-top
   styles in src/input.css. */
(function () {
  'use strict';
  if (document.querySelector('.back-to-top')) return;

  var btn = document.createElement('button');
  btn.type = 'button';
  btn.className = 'back-to-top';
  btn.setAttribute('aria-label', 'Back to top');
  btn.title = 'Back to top';
  btn.innerHTML = '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="square" aria-hidden="true" focusable="false"><path d="M12 19V5"/><path d="m5 12 7-7 7 7"/></svg>';
  document.body.appendChild(btn);

  var reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)');
  var AVOID = '[data-toast], .toast, [data-back-to-top-avoid]';
  var queued = false;

  function isShown(el) {
    var cs = window.getComputedStyle(el);
    return cs.display !== 'none' && cs.visibility !== 'hidden' && parseFloat(cs.opacity) > 0.05;
  }
  function lift() {
    var offset = 0;
    var vw = window.innerWidth;
    var vh = window.innerHeight;
    Array.prototype.forEach.call(document.querySelectorAll(AVOID), function (el) {
      if (!isShown(el)) return;
      var r = el.getBoundingClientRect();
      if (!r.width || !r.height) return;
      if (r.bottom > vh - 140 && r.right > vw - 96 && r.top < vh) offset = Math.max(offset, vh - r.top + 4);
    });
    btn.style.setProperty('--btt-lift', offset + 'px');
  }
  function coversHideZone() {
    var b = btn.getBoundingClientRect();
    return Array.prototype.some.call(document.querySelectorAll('[data-back-to-top-hide]'), function (el) {
      var pos = window.getComputedStyle(el).position;
      if (pos !== 'sticky' && pos !== 'fixed') return false;
      var r = el.getBoundingClientRect();
      return r.width > 0 && r.left < b.right && r.right > b.left && r.top < b.bottom && r.bottom > b.top;
    });
  }
  function update() {
    queued = false;
    btn.classList.toggle('is-visible', window.scrollY > window.innerHeight * 0.9 && !coversHideZone());
    lift();
  }
  function schedule() {
    if (queued) return;
    queued = true;
    window.requestAnimationFrame(update);
  }
  window.addEventListener('scroll', schedule, { passive: true });
  window.addEventListener('resize', schedule);
  update();

  function focusTop() {
    var target = document.getElementById('main') || document.querySelector('main');
    if (!target) return;
    if (!target.hasAttribute('tabindex')) target.setAttribute('tabindex', '-1');
    target.classList.add('back-to-top-target');
    target.focus({ preventScroll: true });
  }
  btn.addEventListener('click', function () {
    if (reduceMotion.matches) {
      window.scrollTo({ top: 0, behavior: 'auto' });
      focusTop();
      return;
    }
    window.scrollTo({ top: 0, behavior: 'smooth' });
    var done = false;
    function finish() {
      if (done) return;
      done = true;
      window.removeEventListener('scrollend', finish);
      focusTop();
    }
    if ('onscrollend' in window) window.addEventListener('scrollend', finish);
    window.setTimeout(finish, 1500);
  });
})();
